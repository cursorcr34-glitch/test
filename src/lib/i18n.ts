export function t(locale: Locale, key: TranslationKey): string {
  return translations[locale][key];
}

export function getDistrictName(district: District, locale: Locale): string {
  const found = DISTRICTS.find((d) => d.id === district);
  if (!found) return district;
  switch (locale) {
    case 'EN':
      return found.nameEn;
    case 'RU':
      return found.nameRu;
    default:
      return found.nameAz;
  }
}

export function getPropertyTypeLabel(type: PropertyType, locale: Locale): string {
  const map: Record<PropertyType, TranslationKey> = {
    APARTMENT: 'typeApartment',
    HOUSE: 'typeHouse',
    COMMERCIAL: 'typeCommercial',
    LAND: 'typeLand',
  };
  return t(locale, map[type]);
}

export function getListingTypeLabel(type: ListingType, locale: Locale): string {
  return type === 'SALE' ? t(locale, 'filterSale') : t(locale, 'filterRent');
}

export function getInquiryStatusLabel(status: InquiryStatus, locale: Locale): string {
  const map: Record<InquiryStatus, TranslationKey> = {
    NEW: 'statusNew',
    CONTACTED: 'statusContacted',
    VIEWING: 'statusViewing',
    NEGOTIATING: 'statusNegotiating',
    CLOSED: 'statusClosed',
    REJECTED: 'statusRejected',
  };
  return t(locale, map[status]);
}

export function getPropertyStatusLabel(status: PropertyStatus, locale: Locale): string {
  const map: Record<PropertyStatus, TranslationKey> = {
    DRAFT: 'statusDraft',
    ACTIVE: 'statusActive',
    SOLD: 'statusSold',
    RENTED: 'statusRented',
    ARCHIVED: 'statusArchived',
  };
  return t(locale, map[status]);
}

export function getRoleLabel(role: Role, locale: Locale): string {
  const map: Record<Exclude<Role, 'ADMIN'>, TranslationKey> = {
    BUYER: 'roleBuyer',
    SELLER: 'roleSeller',
    AGENT: 'roleAgent',
  };
  if (role === 'ADMIN') return locale === 'AZ' ? 'Admin' : locale === 'RU' ? 'Админ' : 'Admin';
  return t(locale, map[role]);
}
